package com.haulwise.solver;

import com.haulwise.solver.model.CostParameters;
import com.haulwise.solver.model.DistanceProvider;
import com.haulwise.solver.model.RouteEvaluation;
import com.haulwise.solver.model.SequencedRoute;
import com.haulwise.solver.model.SequencingMethod;
import com.haulwise.solver.model.Stop;
import com.haulwise.solver.model.TruckSpec;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.Comparator;
import java.util.List;
import java.util.Objects;

/**
 * Chooses the delivery order of one truck's stops that minimises a {@link RouteObjective} (ARCHITECTURE 6.1
 * step 3). Every candidate order is scored by {@link RouteEvaluator}, so fuel (which depends on the load
 * still on board), driving time, service time and the optional return leg all count.
 * <ul>
 *   <li>Up to {@code maxBruteForceStops} stops (default 8 = 40 320 orders): every permutation, generated by
 *       recursive swapping - the result is optimal for the objective.</li>
 *   <li>More stops: nearest neighbour by road distance (ties: lower warehouse id), then best-improvement
 *       2-opt (reverse the segment i..j) on the objective until no move improves it.</li>
 *   <li>When the objective asks for it ({@link RouteObjective#pinnedStopFirst()}), the pinned stop is fixed
 *       at position 1 and only the rest is searched; at most one stop may be pinned then.</li>
 *   <li>Ties: scores are compared at a resolution of {@value #SCORE_RESOLUTION}; equal scores are broken by
 *       the lexicographically smaller warehouse-id sequence. Together with sorting the input by warehouse
 *       id first, the result does not depend on the order of the given stops.</li>
 * </ul>
 * Zero-length legs (co-located warehouses) need no special case: nothing divides by distance and ties fall
 * through to the id rule. Stateless and thread-safe.
 */
public final class StopSequencer {

    public static final int DEFAULT_MAX_BRUTE_FORCE_STOPS = 8;
    /** 9! = 362 880 orders (well under a second): the most a single request may brute-force. */
    public static final int MAX_BRUTE_FORCE_STOPS_LIMIT = 9;
    /** Objective values closer than this count as equal (1/10 000 of a grosz for a PLN cost). */
    static final double SCORE_RESOLUTION = 1e-6;

    private static final Comparator<Stop> BY_WAREHOUSE_ID = Comparator.comparingLong(Stop::warehouseId);

    private final DistanceProvider distances;
    private final RouteEvaluator evaluator;
    private final int maxBruteForceStops;

    public StopSequencer(DistanceProvider distances, CostParameters parameters) {
        this(distances, parameters, DEFAULT_MAX_BRUTE_FORCE_STOPS);
    }

    /**
     * @param maxBruteForceStops largest stop count searched exhaustively, 0..{@value #MAX_BRUTE_FORCE_STOPS_LIMIT}
     */
    public StopSequencer(DistanceProvider distances, CostParameters parameters, int maxBruteForceStops) {
        if (maxBruteForceStops < 0 || maxBruteForceStops > MAX_BRUTE_FORCE_STOPS_LIMIT) {
            throw new IllegalArgumentException("maxBruteForceStops must be 0.." + MAX_BRUTE_FORCE_STOPS_LIMIT
                    + ", was " + maxBruteForceStops);
        }
        this.distances = Objects.requireNonNull(distances, "distances");
        this.evaluator = new RouteEvaluator(distances, parameters);
        this.maxBruteForceStops = maxBruteForceStops;
    }

    /**
     * @param depotId warehouse the truck starts at (and returns to); must not be one of the stops
     * @param stops the truck's stops in any order: distinct warehouses, total drop weight within the payload
     * @param truck the truck driving the route
     * @param returnToDepot whether the empty leg back to the depot is part of the route
     * @param objective what to minimise
     * @throws IllegalArgumentException for an invalid route (see {@link RouteEvaluator#evaluate}) or more than
     *         one pinned stop when the objective fixes the pinned stop first
     */
    public SequencedRoute sequence(long depotId, List<Stop> stops, TruckSpec truck, boolean returnToDepot,
            RouteObjective objective) {
        Objects.requireNonNull(truck, "truck");
        Objects.requireNonNull(objective, "objective");
        RouteContext context = new RouteContext(depotId, truck, returnToDepot, objective);
        List<Stop> start = startOrder(stops, objective);
        int fixedHead = objective.pinnedStopFirst() && start.stream().anyMatch(Stop::pinned) ? 1 : 0;

        if (start.size() <= maxBruteForceStops) {
            return bruteForce(context, start, fixedHead).toRoute(SequencingMethod.BRUTE_FORCE);
        }
        Candidate initial = candidate(context, List.copyOf(nearestNeighbour(depotId, start, fixedHead)));
        return twoOpt(context, initial, fixedHead).toRoute(SequencingMethod.NEAREST_NEIGHBOUR_TWO_OPT);
    }

    /**
     * Greedy order: the first {@code fixedHead} stops stay where they are, then repeatedly the stop nearest
     * (by road km) to the current position, ties broken by lower warehouse id.
     */
    List<Stop> nearestNeighbour(long depotId, List<Stop> stops, int fixedHead) {
        List<Stop> order = new ArrayList<>(stops.subList(0, fixedHead));
        List<Stop> remaining = new ArrayList<>(stops.subList(fixedHead, stops.size()));
        long position = order.isEmpty() ? depotId : order.get(order.size() - 1).warehouseId();
        while (!remaining.isEmpty()) {
            long from = position;
            Stop next = remaining.stream()
                    .min(Comparator.comparingDouble((Stop stop) -> distances.distance(from, stop.warehouseId())
                                    .distanceKm())
                            .thenComparing(BY_WAREHOUSE_ID))
                    .orElseThrow();
            order.add(next);
            remaining.remove(next);
            position = next.warehouseId();
        }
        return order;
    }

    /** Stops sorted by warehouse id; the pinned stop moved to the front when the objective fixes it there. */
    private static List<Stop> startOrder(List<Stop> stops, RouteObjective objective) {
        List<Stop> sorted = new ArrayList<>(Objects.requireNonNull(stops, "stops"));
        sorted.sort(BY_WAREHOUSE_ID);
        if (!objective.pinnedStopFirst()) {
            return sorted;
        }
        List<Stop> pinned = sorted.stream().filter(Stop::pinned).toList();
        if (pinned.size() > 1) {
            throw new IllegalArgumentException("At most one stop can be pinned first, found " + pinned.size()
                    + ": resolve the pin conflict before sequencing");
        }
        if (pinned.size() == 1) {
            sorted.remove(pinned.get(0));
            sorted.add(0, pinned.get(0));
        }
        return sorted;
    }

    private Candidate bruteForce(RouteContext context, List<Stop> start, int fixedHead) {
        return permute(context, start.toArray(Stop[]::new), fixedHead, null);
    }

    /** Tries every arrangement of {@code order[position..]}, keeping {@code order[0..position)} fixed. */
    private Candidate permute(RouteContext context, Stop[] order, int position, Candidate best) {
        if (position >= order.length - 1) {
            return better(candidate(context, Collections.unmodifiableList(Arrays.asList(order))), best);
        }
        Candidate result = best;
        for (int i = position; i < order.length; i++) {
            swap(order, position, i);
            result = permute(context, order, position + 1, result);
            swap(order, position, i);
        }
        return result;
    }

    /** Best-improvement 2-opt: apply the best segment reversal while one improves the objective. */
    private Candidate twoOpt(RouteContext context, Candidate initial, int fixedHead) {
        int size = initial.stops().size();
        Candidate current;
        Candidate best = initial;
        do {
            current = best;
            for (int i = fixedHead; i < size - 1; i++) {
                for (int j = i + 1; j < size; j++) {
                    best = better(candidate(context, reversed(current.stops(), i, j)), best);
                }
            }
        } while (best != current);
        return current;
    }

    private Candidate candidate(RouteContext context, List<Stop> order) {
        RouteEvaluation evaluation = evaluator.evaluate(context.depotId(),
                order.stream().map(Stop::toRouteStop).toList(), context.truck(), context.returnToDepot());
        double score = context.objective().score(order, evaluation);
        if (!Double.isFinite(score)) {
            throw new IllegalStateException("Objective returned " + score + " for " + order);
        }
        return new Candidate(order, evaluation, score);
    }

    /** The better of the two; a winning candidate is copied, as its order may be a view of a reused array. */
    private static Candidate better(Candidate candidate, Candidate best) {
        return best == null || candidate.isBetterThan(best) ? candidate.snapshot() : best;
    }

    private static List<Stop> reversed(List<Stop> stops, int from, int to) {
        List<Stop> copy = new ArrayList<>(stops);
        Collections.reverse(copy.subList(from, to + 1));
        return Collections.unmodifiableList(copy);
    }

    private static void swap(Stop[] order, int a, int b) {
        Stop tmp = order[a];
        order[a] = order[b];
        order[b] = tmp;
    }

    private record RouteContext(long depotId, TruckSpec truck, boolean returnToDepot, RouteObjective objective) {
    }

    private record Candidate(List<Stop> stops, RouteEvaluation evaluation, double score) {

        /** Lower score at {@link #SCORE_RESOLUTION}, then the lexicographically smaller warehouse-id sequence. */
        boolean isBetterThan(Candidate other) {
            int byScore = Double.compare(roundedScore(), other.roundedScore());
            if (byScore != 0) {
                return byScore < 0;
            }
            for (int i = 0; i < stops.size(); i++) {
                int byId = Long.compare(stops.get(i).warehouseId(), other.stops().get(i).warehouseId());
                if (byId != 0) {
                    return byId < 0;
                }
            }
            return false;
        }

        private double roundedScore() {
            return Math.rint(score / SCORE_RESOLUTION);
        }

        Candidate snapshot() {
            return new Candidate(List.copyOf(stops), evaluation, score);
        }

        SequencedRoute toRoute(SequencingMethod method) {
            return new SequencedRoute(stops, evaluation, score, method);
        }
    }
}
